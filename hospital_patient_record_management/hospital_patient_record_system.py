import csv
import os
import datetime
from abc import ABC, abstractmethod

# Custome Exception
class PatientNotFoundError(Exception):
  """Raised when a patient ID does not exist in the system"""
  pass

class DuplicatePatientError(Exception):
  """Raised when attempting to register an existing patient ID."""
  pass

class InvalidBillingError(Exception):
  """Raised for non positive medical charges or invalid day counts."""
  pass

#Abstarction base class

class Patient(ABC):
  """Abstarction base class representing a registered hospital patient."""
  def __init__(self, patient_id:str,name:str, age:int, diagnosis:str):
    self._patient_id = patient_id
    self._name = name
    self._age = age
    self.__diagnosis = diagnosis

  @property
  def patient_id(self)->str:
    return self._patient_id
  @property
  def name(self)->str:
    return self._name
  @name.setter
  def name(self,value:str):
    if not value.strip():
      raise ValueError("Patient name cannot be empty.")
    self._name = value.strip()
  @property
  def age(self)->int:
    return self._age
  @age.setter
  def age(self,val:int):
    if val<=0 or val>125:
      raise ValueError("Age must be between 1 and 125.")
    self._age=val
  @property
  def diagnosis(self)->str:
    return self.__diagnosis
  @diagnosis.setter
  def diagnosis(self, new_diag:str):
    if not new_diag.strip():
      raise ValueError("Diagnosis cannot be empty.")
    self.__diagnosis=new_diag.strip()
  @abstractmethod
  def calculate_bill(self)->float:
    """Calculates total medical expenses incurred."""
    pass
  def get_summary(self)->str:
    """Generates a complete patient overview."""
    pass

#Inheritance and Encapsulation subclass

class InpatientRecord(Patient):
  """Admitted hospital patient incurring daily room and treatment costs."""
  def __init__(self, patient_id:str,name:str,age:int,diagnosis:str,days_admitted:int,daily_rate:float,treatment_charge:float):
    super().__init__(patient_id,name,age,diagnosis)
    self.set_stay_details(days_admitted,daily_rate,treatment_charge)
  def set_stay_details(self, days_admitted:int,daily_rate:float,treatment_charge:float):
    if days_admitted<=0:
      raise InvalidBillingError("Number of days must be positive.")
    if daily_rate<=0 or treatment_charge<0:
      raise InvalidBillingError("Rates must be positive.")
    self.__days_admitted = days_admitted
    self.__daily_rate = round(daily_rate,2)
    self.__treatment_charge = round(treatment_charge,2)
  @property
  def days_admitted(self)->int:
    return self.__days_admitted
  @property
  def daily_rate(self)->float:
    return self.__daily_rate
  @property
  def treatment_charge(self)->float:
    return self.__treatment_charge

  def calculate_bill(self) -> float:
    room_cost=self.__days_admitted*self.__daily_rate
    return round(room_cost+self.__treatment_charge,2)
  def get_summary(self)->str:
    return(
        f"Type: Inpatient  | ID: {self.patient_id:<8} | Name: {self.name:<18} | Age: {self.age:<3} | "
            f"Diagnosis: {self.diagnosis:<15} | Days: {self.__days_admitted:<2} | Bill: ₹{self.calculate_bill():<9.2f}"
    )

class OutpatientRecord(Patient):
  """ Consultation -only patient incurring OPD and diagnostic lab fees."""
  def __init__(self, patient_id:str,name:str,age:int,diagnosis:str,consultation_fee:float, lab_fee:float=0.0):
    super().__init__(patient_id,name,age,diagnosis)
    self.set_fees(consultation_fee,lab_fee)
  def set_fees(self,consultation_fee:float,lab_fee:float):
    if consultation_fee <= 0 or lab_fee < 0:
      raise InvalidBillingError("Consultation and lab fees must be positive.")
    self.__consultation_fee = round(consultation_fee, 2)
    self.__lab_fee = round(lab_fee, 2)
  @property
  def consultation_fee(self)->float:
    return self.__consultation_fee
  @property
  def lab_fee(self)->float:
    return self.__lab_fee
  def calculate_bill(self) -> float:
    return round(self.__consultation_fee + self.__lab_fee, 2)
  def get_summary(self) -> str:
    return (
    f"Type: Outpatient | ID: {self.patient_id:<8} | Name: {self.name:<18} | Age: {self.age:<3} | "
    f"Diagnosis: {self.diagnosis:<15} | Lab: ₹{self.__lab_fee:<6.2f} | Bill: ₹{self.calculate_bill():<9.2f}"
        )

#Management Class: HospitalManager

class HospitalManager:
    """Manages patient admission directories, queries, and CSV persistence."""

    def __init__(self, filename: str = "patient_records.csv"):
        self.filename = filename
        self.patients: dict[str, Patient] = {}
        self.load_from_file()

    def register_inpatient(
        self,
        p_id: str,
        name: str,
        age: int,
        diag: str,
        days: int,
        daily_rate: float,
        treatment: float,
    ):
        if p_id in self.patients:
            raise DuplicatePatientError(f"Patient ID '{p_id}' is already registered.")
        p = InpatientRecord(p_id, name, age, diag, days, daily_rate, treatment)
        self.patients[p_id] = p
        print(f"✓ Inpatient '{name}' registered successfully.")

    def register_outpatient(
        self,
        p_id: str,
        name: str,
        age: int,
        diag: str,
        consult: float,
        lab: float,
    ):
        if p_id in self.patients:
            raise DuplicatePatientError(f"Patient ID '{p_id}' is already registered.")
        p = OutpatientRecord(p_id, name, age, diag, consult, lab)
        self.patients[p_id] = p
        print(f"✓ Outpatient '{name}' registered successfully.")

    def search_patient(self, p_id: str) -> Patient:
        if p_id not in self.patients:
            raise PatientNotFoundError(f"Patient with ID '{p_id}' was not found.")
        return self.patients[p_id]

    def update_diagnosis(self, p_id: str, new_diag: str):
        patient = self.search_patient(p_id)
        patient.diagnosis = new_diag
        print(f"✓ Diagnosis for patient '{p_id}' updated to '{new_diag}'.")

    def discharge_patient(self, p_id: str):
        patient = self.search_patient(p_id)
        final_bill = patient.calculate_bill()
        del self.patients[p_id]
        print(f"✓ Patient '{patient.name}' discharged. Final settled bill: ₹{final_bill:,.2f}")

    def display_all(self):
        if not self.patients:
            print("No active patient records on file.")
            return

        print("\n" + "=" * 90)
        print("HOSPITAL ACTIVE PATIENT DIRECTORY".center(90))
        print("=" * 90)
        total_billing = 0.0
        for p in self.patients.values():
            print(p.get_summary())
            total_billing += p.calculate_bill()
        print("-" * 90)
        print(f"Total Outstanding Medical Receivables: ₹{total_billing:,.2f}")
        print("=" * 90)

    # --- File Handling (CSV) ---
    def save_to_file(self):
        try:
            with open(self.filename, mode="w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow(
                    ["type", "id", "name", "age", "diagnosis", "p1", "p2", "p3"]
                )
                for p in self.patients.values():
                    if isinstance(p, InpatientRecord):
                        writer.writerow(
                            [
                                "Inpatient",
                                p.patient_id,
                                p.name,
                                p.age,
                                p.diagnosis,
                                p.days_admitted,
                                p.daily_rate,
                                p.treatment_charge,
                            ]
                        )
                    elif isinstance(p, OutpatientRecord):
                        writer.writerow(
                            [
                                "Outpatient",
                                p.patient_id,
                                p.name,
                                p.age,
                                p.diagnosis,
                                p.consultation_fee,
                                p.lab_fee,
                                0.0,
                            ]
                        )
            print(f"✓ Patient records safely persisted to '{self.filename}'.")
        except IOError as e:
            print(f"File Error: Failed to save records ({e}).")

    def load_from_file(self):
        if not os.path.exists(self.filename):
            return

        try:
            with open(self.filename, mode="r", newline="", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    p_type = row["type"]
                    p_id = row["id"]
                    name = row["name"]
                    age = int(row["age"])
                    diag = row["diagnosis"]
                    p1 = float(row["p1"])
                    p2 = float(row["p2"])
                    p3 = float(row.get("p3", 0.0))

                    if p_type == "Inpatient":
                        self.patients[p_id] = InpatientRecord(
                            p_id, name, age, diag, int(p1), p2, p3
                        )
                    elif p_type == "Outpatient":
                        self.patients[p_id] = OutpatientRecord(
                            p_id, name, age, diag, p1, p2
                        )
        except (IOError, KeyError, ValueError) as e:
            print(f"Warning: Issue reading '{self.filename}' ({e}). Starting fresh.")

